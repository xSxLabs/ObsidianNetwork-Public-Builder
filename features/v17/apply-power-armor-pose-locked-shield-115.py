#!/usr/bin/env python3
"""Build115: match armor's six actual avatar joints with vanilla model orientation.

Build114 already correctly obtains the posed AvatarRenderer model and rotates
with render state bodyRot. But Build113's X=+1 mirror removal differs from
Minecraft's own player/armor model (-1,-1,1), so head local yaw was reversed
relative to the armor. Restore vanilla's root parity WITH Build114 body facing;
no separate head angles, no fake motion or cardinal-direction exceptions.
Also make the energy field breathe smoothly over ~7.5 seconds: fade between
nearly invisible and gently blue, retain the strong damage flash.
Only the client-renderer Java generated by Builds106-114 is touched.
"""
import os
from pathlib import Path

p=Path(os.environ["V1_SOURCE_ROOT"])/"dev/obsidiannetwork/client/PowerArmorShieldClient.java"
s=p.read_text(encoding="utf-8")
for required in ("BUILD111_POSED_ARMOR_SHIELD", "BUILD112_MODEL_COORDS",
                 "BUILD113_UNMIRRORED_ANIMATION","BUILD114_BODY_FACING_LOCK"):
 assert required in s, required

# The effective root now matches the model-space transformation used to draw
# the armor. model.head/body/rightArm/leftArm/rightLeg/leftLeg are already posed
# by AvatarRenderer.setupAnim in the SAME frame; joint.translateAndRotate()
# therefore reuses the exact angles. Do NOT negate individual head angles.
old='''  // BUILD113_UNMIRRORED_ANIMATION: keep vertical model correction, but DO
  // NOT apply an additional horizontal reflection to the already-oriented
  // player pose. Otherwise head yaw and lateral arm/leg poses run backward.
  stack.scale(1.0F,-1.0F,1.0F);
  stack.translate(0.0F,-1.501F,0.0F);'''
new='''  // BUILD115_ARMOR_POSE_LOCK: EXACT vanilla player / armor model root
  // transform. The animated ModelParts above are the very same joints used
  // by the avatar armor layer; preserving X=-1 ensures head yaw, pitch, body
  // movement and limb swing share the armor's handedness at EVERY facing.
  // The 180-bodyRot yaw from Build114 must remain OUTSIDE this transform.
  stack.scale(-1.0F,-1.0F,1.0F);
  stack.translate(0.0F,-1.501F,0.0F);'''
assert s.count(old)==1, ("root transform drift",s.count(old))
s=s.replace(old,new,1)

oldPulse='''  float pulse=(float)(.5D+.5D*Math.sin(time*.075D));
  // Damaging the Build104 forcefield visibly illuminates ALL six shell parts.
  float impact=Math.min(1F,Math.max(0F,wearer.hurtTime-event.getPartialTick())/8F);
  int alpha=Math.min(236,(int)(60F+9F*pulse+165F*impact));'''
newPulse='''  // BUILD115_SLOW_BLUE_BREATH: a continuous 7.5-second sine cycle.
  // Smoothstep flattens both ends: no hard flicker or abrupt alpha/color jump.
  float phase=(float)(.5D+.5D*Math.sin(time*.042D));
  float breathe=phase*phase*(3F-2F*phase);
  // Build104 remains authoritative for every absorbed hit and its FE cost.
  // Keep the bright flash on impact on top of the calm breathing effect.
  float impact=Math.min(1F,Math.max(0F,wearer.hurtTime-event.getPartialTick())/8F);
  int alpha=Math.min(247,(int)(41F+58F*breathe+157F*impact));'''
assert s.count(oldPulse)==1,("idle alpha block drift",s.count(oldPulse))
s=s.replace(oldPulse,newPulse,1)

oldWave='''    float ripple=(float)(.5D+.5D*Math.sin(time*.45D+i*.38D-j*.51D));
    int opacity=Math.min(255,alpha+(int)(hit*25F*ripple));'''
newWave='''    float ripple=(float)(.5D+.5D*Math.sin(time*.45D+i*.38D-j*.51D));
    // A tiny, slow moving highlight across the hex membrane; far gentler
    // than the original rapid spark effect and subordinate to the main fade.
    float flow=(float)(.5D+.5D*Math.sin(time*.040D+i*.19D-j*.13D));
    int opacity=Math.min(255,alpha+(int)(4F*flow)+(int)(hit*25F*ripple));'''
assert s.count(oldWave)==1,("membrane wave drift",s.count(oldWave))
s=s.replace(oldWave,newWave,1)

# Slightly bluer than Build114's cyan (93,221,255). Only tint, no texture edits.
assert s.count(".setColor(93,221,255,alpha)")==1
s=s.replace(".setColor(93,221,255,alpha)",".setColor(92,194,255,alpha)",1)

# The whole suit rotates together, and every animated ModelPart is exactly the
# one rendered by AvatarRenderer, with ZERO custom joint-angle overrides.
assert s.count("stack.mulPose(Axis.YP.rotationDegrees(180.0F-state.bodyRot));")==1
assert s.count("stack.scale(-1.0F,-1.0F,1.0F);")==1
assert "stack.scale(1.0F,-1.0F,1.0F);" not in s
assert s.index("stack.mulPose(Axis.YP.rotationDegrees(180.0F-state.bodyRot));") < s.index("stack.scale(-1.0F,-1.0F,1.0F);") < s.index("submitPart(stack,collector,model.head")
assert s.count("submitPart(stack,collector,model.")==6
assert s.count("joint.translateAndRotate(stack);")==1
assert "model.head.yRot=" not in s and "model.head.xRot=" not in s
assert "phase*phase*(3F-2F*phase)" in s
assert "EnergyTool.energy(armor)<20L" in s
assert 'id.equals("energy_shield")' in s
assert "float impact=Math.min" in s

p.write_text(s,encoding="utf-8")

# Compare yaw sign in the exact vanilla body frame: rotating the head around
# model +Y makes local front -Z move toward negative X. The model X flip
# restores positive world X. Build113's X=+1 reversed it.
import math
yaw=.25
local_head_x=-math.sin(yaw)
assert -local_head_x>0
assert +local_head_x<0
# Smoothstep profile: monotonic, bounded, and continuous at both ends.
def smooth(x):return x*x*(3-2*x)
assert smooth(0)==0 and smooth(1)==1 and smooth(.5)==.5
assert all(smooth(i/100)<=smooth((i+1)/100) for i in range(100))
print("BUILD115_ARMOR_POSE_LOCK PASS: vanilla armor pose handedness and all six body joints, smoothly breathing blue hex field, hit flash/FE untouched")
