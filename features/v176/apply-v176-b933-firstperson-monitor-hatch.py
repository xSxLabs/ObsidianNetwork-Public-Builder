#!/usr/bin/env python3
"""B933: correct actual first-person empty-hand gun submission, client-side
Power Monitor ghost hitboxes, unwanted Powerbank switch, true rear casing,
and floating hatch while preserving working third-person aim and front face.
Runs AFTER B929, and fails closed on all source contracts.
"""
import os,json,re,colorsys
from pathlib import Path
from PIL import Image
J=Path(os.environ["V1_SOURCE_ROOT"])/"dev/obsidiannetwork"
A=Path(os.environ["V1_RESOURCE_ROOT"])/"assets/obsidiannetwork"

def edit(path,old,new):
 p=J/path
 s=p.read_text(encoding="utf-8")
 assert s.count(old)==1,("B933_DRIFT",path,s.count(old),old[:110])
 p.write_text(s.replace(old,new,1),encoding="utf-8")

# B929 previously disabled 54 placeholder ChestMenu slots only on SERVER,
# but generic_9x6 is instantiated as plain ChestMenu on the CLIENT. Replacing
# the screen does NOT replace its menu slots, so a second hidden clickable grid
# remained behind the GUI. Hide those exact 54 slots in the actual client menu.
# Preserve slots 54..89 (3x9 inventory and 1x9 hotbar) untouched.
screen="client/V176PowerMonitorScreen.java"
edit(screen,
 """  super(menu,inv,title);
  BlockPos pos=null;""",
 """  super(menu,inv,title);
  // Server's custom menu does not instantiate on client: generic_9x6
  // creates regular ChestMenu. Its 54 phantom slots MUST be disabled here.
  for(int id=0;id<54;id++){
   net.minecraft.world.inventory.Slot original=(net.minecraft.world.inventory.Slot)this.menu.slots.get(id);
   this.menu.slots.set(id,new net.minecraft.world.inventory.Slot(
       original.container,original.getContainerSlot(),-10000,-10000){
    @Override public boolean isActive(){return false;}
    @Override public boolean mayPlace(net.minecraft.world.item.ItemStack stack){return false;}
    @Override public boolean mayPickup(net.minecraft.world.entity.player.Player player){return false;}
   });
  }
  BlockPos pos=null;""")
# Powerbanks have no ON/OFF switch on the monitor screen per user spec.
# Reactors still retain their original ON/OFF status + toggle command.
edit(screen,
 "   g.text(font,state,153,y+3,d.enabled()?0xff7bffb0:0xffff9595);",
 """   if(d.type()==V176PowerMonitorRules.DeviceType.REACTOR)
    g.text(font,state,153,y+3,d.enabled()?0xff7bffb0:0xffff9595);""")
edit(screen,
 """      var d=list.get(idx);
      var mc=Minecraft.getInstance();""",
 """      var d=list.get(idx);
      // No hidden Powerbank toggle behind an invisible ON/OFF button.
      if(d.type()!=V176PowerMonitorRules.DeviceType.REACTOR)return true;
      var mc=Minecraft.getInstance();""")
# Remove the former ON/OFF switch button background from Powerbank rows too.
edit(screen,
 "   g.fill(x+148,ry+2,x+171,ry+16,0xff30566b);",
 """   var snapshot=live();
   if(snapshot!=null&&page*ROWS+i<snapshot.devices().size()&&
       snapshot.devices().get(page*ROWS+i).type()==V176PowerMonitorRules.DeviceType.REACTOR)
    g.fill(x+148,ry+2,x+171,ry+16,0xff30566b);""")
# The server command must agree with the UI: Powerbanks are read-only in
# Power Monitor. Existing Powerbank hardware controls remain untouched.
graph="power/V176PowerNetworkGraph.java"
edit(graph,
 """  if(world.getBlockEntity(target) instanceof PowerbankBlockEntity bank
     &&bank.mode()==PowerbankBlock.Mode.CONTROLLER){
   bank.xsxNetworkSetEnabled(!bank.xsxNetworkEnabled());
   return true;
  }""",
 """  // No Powerbank ON/OFF via the Power Monitor, including direct commands.
""")
# B929 made the rear an unrelated white copy of the front. User explicitly
# wants the REAR texture to be identical to the original TOP casing instead.
# The accepted NORTH front is never changed or regenerated by this patch.
model=A/"models/block/power_terminal.json"
m=json.loads(model.read_text(encoding="utf-8"))
assert m["textures"]["north"]=="obsidiannetwork:block/power_terminal_computer_front"
# The preceding monitor patch may already set SOUTH to the TOP casing.
# This operation is deliberately idempotent; only the NORTH front is fixed.
assert "up" in m["textures"] and m["textures"]["up"]
m["textures"]["south"]=m["textures"]["up"]
model.write_text(json.dumps(m,indent=2)+"\n",encoding="utf-8")

# All 24 Backpack variants use a BLACK shell and straps. Each tier retains a
# distinct colored accent on trim/buckles/lights; do not touch items, storage,
# recipes, module slots or capacity. Four distinct UV material textures avoid
# previous recoloring accidentally bleeding into body faces.
for tier in range(1,25):
 name=f"network_backpack_mk{tier}"
 target=A/"models/block"/f"{name}.json"
 data=json.loads(target.read_text(encoding="utf-8"))
 assert all(k in data["textures"] for k in ("body","dark","accent","glow")),("B935_BACKPACK_MODEL",tier)
 rgb=colorsys.hsv_to_rgb(((tier-1)/24.0+0.015)%1.0,0.82,0.9)
 accent=tuple(int(v*255) for v in rgb)
 glow=tuple(min(255,int(v*0.8+61)) for v in accent)
 palette={"body":(18,20,24),"dark":(7,9,12),"accent":accent,"glow":glow}
 for material,color in palette.items():
  img=Image.new("RGBA",(16,16))
  pix=img.load()
  for y in range(16):
   for x in range(16):
    delta=-6 if (x*3+y*5)%7==0 else 3 if (x+y)%5==0 else 0
    pix[x,y]=(*(max(0,min(255,v+delta)) for v in color),255)
  basename=f"{name}_{material}"
  img.save(A/"textures/block"/f"{basename}.png",optimize=True)
  data["textures"][material]="obsidiannetwork:block/"+basename
 target.write_text(json.dumps(data,indent=2)+"\n",encoding="utf-8")


# B917 ERRONEOUSLY rejected empty main hand, exactly the normal Attack Mode
# configuration. Draw from RenderHandEvent for main hand regardless of item.
# Keep the arm's own RenderArmEvent strictly responsible for posing/moving
# the vanilla arm to avoid a second, incorrectly transformed duplicate gun.
gun="client/V176MicroMgVisualClient.java"
edit(gun,
 "  if(progress<=0.001F||event.getItemStack().isEmpty())return;",
 """  if(progress<=0.001F)return;
  // RenderHandEvent executes BEFORE vanilla hand drawing: translate the
  // shared hand frame so the *real arm* and the submitted gun move together.
  event.getPoseStack().translate(-0.21F,0.04F,-0.02F);""")
edit(gun,
 "  pose.translate(0.58F,-0.30F,-0.53F);",
 "  pose.translate(0.43F,-0.30F,-0.53F);")
# Existing 1P arm pose is still down/right according to B931 ingame images.
# Raise the genuine arm further and move it left. 3P model setup is untouched.
edit(gun,
 "  pose.translate(-0.25F,0.10F,-0.18F);",
 "  pose.translate(-0.16F,0.14F,-0.27F);")
edit(gun,
 "  pose.mulPose(com.mojang.math.Axis.XP.rotationDegrees(-50.0F));",
 "  pose.mulPose(com.mojang.math.Axis.XP.rotationDegrees(-78.0F));")
# The mount cap is a 4.2-model-pixel black rectangle beside the helmet.
# Keep the slim barrel, reduce only the cap to a tiny attachment on upper arm.
edit(gun,
 "      .texOffs(0,15).addBox(-1.12F,3.5F,-3.05F,2.24F,4.2F,0.65F)",
 "      .texOffs(0,15).addBox(-0.35F,5.0F,-3.05F,0.70F,1.10F,0.24F)")
p=J/gun
s=p.read_text(encoding="utf-8")
start=" @SubscribeEvent public static void xsxlabs$aimVisibleFirstPersonArm(RenderArmEvent event){"
end=" @SubscribeEvent public static void worldSuit("
assert s.count(start)==1 and s.count(end)==1
a=s.index(start); b=s.index(end,a)
chunk=s[a:b]
needle="  float gunOut=phase(progress,7.0F/12.0F,1.0F);"
assert chunk.count(needle)==1
cut=chunk.index(needle)
assert "event.getSubmitNodeCollector().submitModelPart(BARREL,pose" in chunk[cut:]
# Match only the body of the arm callback, not the hand's barrel renderer.
chunk=chunk[:cut]+"""  // RenderArmEvent changes only the genuine right arm's camera transform.
  // The visible gun is drawn exactly once in RenderHandEvent, including
  // an EMPTY main hand. No orphan duplicate mesh at the shoulder/head.
 }
"""
s=s[:a]+chunk+s[b:]
# Disable the older held-item-only auxiliary renderer so it cannot submit
# a second, stale gun. Its behavior is subsumed by main firstPerson handler.
start=" @SubscribeEvent public static void firstPersonWithItem(RenderHandEvent event){"
end=" @SubscribeEvent public static void worldSuit("
assert s.count(start)==1 and s.count(end)==1,("B933_OLD_HAND_HANDLER_DRIFT",s.count(start),s.count(end))
a=s.index(start);b=s.index(end,a)
assert a<b
s=s[:a]+s[b:]
# The black freestanding plate in steady Attack Mode is not an acceptable
# hatch: show hinged hatch ONLY during its actual opening/closing phase.
# Retain the original arm/barrel model and third-person aim unchanged.
part_begin=" public static void drawArm("
part_end=" private static void drawRight("
assert s.count(part_begin)==1 and s.count(part_end)==1
a=s.index(part_begin);b=s.index(part_end,a)
part=s[a:b]
part,count=re.subn(r'if\s*\(\s*hatchOpen\s*>\s*0\.001F\s*\)',
                    'if(hatchOpen>0.001F&&hatchOpen<0.999F)',part)
assert count==1,("B933_HATCH_DRAW_DRIFT",count)
s=s[:a]+part+s[b:]
p.write_text(s,encoding="utf-8")

screen_src=(J/screen).read_text(encoding="utf-8")
gun_src=(J/gun).read_text(encoding="utf-8")
menu=(J/"power/V176PowerTerminalMenu.java").read_text(encoding="utf-8")
assert "for(int id=0;id<54;id++)" in screen_src
