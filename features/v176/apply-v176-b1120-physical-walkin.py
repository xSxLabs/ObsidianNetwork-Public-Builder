from pathlib import Path

def one(src,old,new,name):
    n=src.count(old)
    assert n==1,("B1120_SOURCE_DRIFT",name,n,old[:130])
    return src.replace(old,new,1)

def visual_patch(s):
    # All cosmetic armor visuals are constructed on BOTH server and client.
    # Server-side view.noPhysics alone does not prevent client prediction from
    # treating the open suit's visual as an obstructing ArmorStand entity.
    pattern=r'(public\s+PowerArmorVisualEntity\s*\([^{}]*\)\s*\{\s*super\([^;{}]*\);)'
    found=list(re.finditer(pattern,s))
    assert len(found)==1,("B1123_VISUAL_CTOR_DRIFT",len(found))
    m=found[0]
    result=s[:m.end()]+"\n  this.noPhysics=true; // visual cannot obstruct physical walk-in"+s[m.end():]
    assert result.count("this.noPhysics=true; // visual cannot obstruct physical walk-in")==1
    return result

def entry_patch(s):
    # B1121: B657 NeoForge API uses public noPhysics, not setMarker.
    # Recover an already-stuck world stand to default noPhysics=false.
    s=one(s,
'''  boolean originalMarker=stand.noPhysics;
  stand.addTag(OPEN_TAG);''',
'''  boolean originalMarker=false; // owned world suit's normal physics state
  stand.addTag(OPEN_TAG);''',"legacy-noPhysics-on-click")
    # Ownership never changes until PowerArmorSuitWorld transaction commits.
    # The visual is an extra cosmetic overlay and is physically nonblocking.
    # noPhysics preserves visible owner without making it a marker (markers
    # have special rendering/picking semantics in Minecraft).
    s=one(s,
'''  view.addTag("xsxlabs_b655_entry_hold_visual");
  view.begin(true);view.beginPhase(8);''',
'''  view.addTag("xsxlabs_b655_entry_hold_visual");
  view.noPhysics=true; // cosmetic shell can NEVER block actual walk-in
  view.begin(true);view.beginPhase(8);''',"visual-nocollision")
    s=one(s,
'''  stand.addTag(OPEN_TAG);
  stand.addTag(HIDE_TAG);
  stand.setInvisible(true);
  stand.noPhysics=true;  // vanilla ArmorStand passes through player while open''',
'''  stand.addTag(OPEN_TAG);
  stand.removeTag(HIDE_TAG); // no hidden original while waiting
  stand.setInvisible(false);
  stand.noPhysics=true; // pass-through but renders the item-owning suit''',"visible-world-owner")
    # The frozen B657 method is generated by multiple stages with formatting
    # changes. Patch by signature and guarded semantic tokens, never by a
    # whitespace-fragile string. Refuse any unrelated method drift.
    pattern=r'private\s+static\s+boolean\s+inside\s*\(\s*ServerPlayer\s+p\s*,\s*ArmorStand\s+stand\s*\)\s*\{[^}]*\}'
    matches=list(re.finditer(pattern,s))
    assert len(matches)==1,("B1120_INSIDE_METHOD_COUNT",len(matches))
    match=matches[0]
    old=s[match.start():match.end()]
    for token in ("getX()","getZ()","getY()",".22D",".65D"):
        assert token in old,("B1120_OLD_GEOMETRY_DRIFT",token)
    newer="""private static boolean inside(ServerPlayer p,ArmorStand stand){
   // 0.469-block old center threshold rejected humans at model shell.
   double dx=p.getX()-stand.getX(),dz=p.getZ()-stand.getZ();
   double dy=p.getY()-stand.getY();
   return dx*dx+dz*dz<=.81D && dy>=-.40D && dy<=1.30D;
  }"""
    s=s[:match.start()]+newer+s[match.end():]
    # Keep the real owner visible while OPEN. The closing and rollback
    # protections from B1107 remain authoritative.
    s=one(s,
'''  if(!inside(p,stand))return;
  // Revalidate AT THE PHYSICAL STEP.''',
'''  if(!inside(p,stand)){
   if(p.tickCount%20==0)org.slf4j.LoggerFactory.getLogger("xSxLabs/PowerArmorEntry")
      .info("B1120_MANUAL_ENTRY_WAIT player={} suitId={} dx={} dy={} dz={} realVisible={} visualAlive={}",
       p.getName().getString(),stand.getId(),
       String.format(java.util.Locale.ROOT,"%.2f",p.getX()-stand.getX()),
       String.format(java.util.Locale.ROOT,"%.2f",p.getY()-stand.getY()),
       String.format(java.util.Locale.ROOT,"%.2f",p.getZ()-stand.getZ()),
       !stand.isInvisible(),!opened.visual().isRemoved());
   return;
  }
  // Revalidate AT THE PHYSICAL STEP.''',"wait-coordinates")
    assert "stand.setInvisible(true);" not in s, "B1120 real stand must never hide"
    assert "stand.noPhysics=true;" in s
    assert "PowerArmorSuitWorld.tryEnter(p,stand.getId());" in s
    return s

